#!/usr/bin/env node
// Generates src/design-system/aapm-tokens.css from the AAPM Academy token
// authority. Run `npm run tokens` after editing the JSON; `--check` exits
// non-zero when the committed CSS is stale (used by the test suite).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const sourcePath = new URL("src/design-system/tokens/aapm-academy.tokens.json", root);
const outputPath = new URL("src/design-system/aapm-tokens.css", root);

export function kebab(name) {
  return name
    .replace(/_/g, "-")
    .replace(/([a-z])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();
}

const layerPrefix = { primitive: "primitive", semantic: "semantic", component: "component" };
const refPattern = /^\{(primitive|semantic|component)\.([^}]+)\}$/;

function resolve(tokens, value, appearance, seen = new Set()) {
  const match = refPattern.exec(value);
  if (!match) return value;
  const [, layer, name] = match;
  const key = `${layer}.${name}`;
  if (seen.has(key)) throw new Error(`Circular AAPM token: ${key}`);
  seen.add(key);
  const collection = layer === "semantic" ? tokens.semantic[appearance] : tokens[layer];
  const next = collection?.[name];
  if (next === undefined) throw new Error(`Unknown AAPM token: ${key}`);
  return resolve(tokens, next, appearance, seen);
}

/** A reference stays a live var() so components follow the active theme. */
function cssValue(tokens, value) {
  const match = refPattern.exec(value);
  if (!match) return value;
  const [, layer, name] = match;
  const collection = layer === "semantic" ? tokens.semantic.light : tokens[layer];
  if (collection?.[name] === undefined) throw new Error(`Unknown AAPM token: ${layer}.${name}`);
  return `var(--aapm-${layerPrefix[layer]}-${kebab(name)})`;
}

function hexToHslChannels(hex) {
  const clean = hex.replace("#", "");
  const full = clean.length === 3 ? clean.split("").map((c) => c + c).join("") : clean;
  if (!/^[0-9a-f]{6}$/i.test(full)) throw new Error(`Bridge tokens must resolve to hex colors: ${hex}`);
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0;
  let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
  }
  const round = (value, digits = 1) => Number(value.toFixed(digits));
  return `${round(h)} ${round(s * 100)}% ${round(l * 100)}%`;
}

export function buildTokenCss(tokens) {
  const lines = [
    "/* Generated by scripts/build-aapm-tokens.mjs from",
    " * src/design-system/tokens/aapm-academy.tokens.json. Do not edit by hand. */",
    "",
    ":root {",
  ];
  for (const [name, value] of Object.entries(tokens.primitive)) {
    lines.push(`  --aapm-primitive-${kebab(name)}: ${value};`);
  }
  for (const [name, value] of Object.entries(tokens.component)) {
    lines.push(`  --aapm-component-${kebab(name)}: ${cssValue(tokens, value)};`);
  }
  lines.push("}", "");

  const themeBlock = (selector, appearance) => {
    lines.push(`${selector} {`, `  color-scheme: ${appearance};`);
    for (const [name, value] of Object.entries(tokens.semantic[appearance])) {
      lines.push(`  --aapm-semantic-${kebab(name)}: ${cssValue(tokens, value)};`);
    }
    lines.push("  /* Legacy shadcn/Tailwind bridge (HSL channels). */");
    for (const [name, value] of Object.entries(tokens.bridge.vars)) {
      lines.push(`  --${name}: ${hexToHslChannels(resolve(tokens, value, appearance))};`);
    }
    lines.push("}", "");
  };
  themeBlock(':root,\n[data-theme="light"]', "light");
  themeBlock('.dark,\n[data-theme="dark"]', "dark");
  return lines.join("\n");
}

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isCli) {
  const tokens = JSON.parse(readFileSync(sourcePath, "utf8"));
  const css = buildTokenCss(tokens);
  if (process.argv.includes("--check")) {
    const current = readFileSync(outputPath, "utf8");
    if (current !== css) {
      console.error("aapm-tokens.css is stale. Run `npm run tokens`.");
      process.exit(1);
    }
    console.log("aapm-tokens.css is up to date.");
  } else {
    writeFileSync(outputPath, css);
    console.log(`Wrote ${fileURLToPath(outputPath)}`);
  }
}
